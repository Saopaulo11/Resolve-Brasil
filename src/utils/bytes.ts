/**
 * Предел размера файла в мегабайтах — для текста на странице.
 *
 * Человеку у формы нужен порядок величины, а не точное число байт: «до 10 MB»
 * читается, «до 10485760 байт» — нет. Округляем вниз, чтобы названный предел
 * не оказался больше настоящего: файл ровно на названный размер должен
 * приниматься, иначе подпись врёт.
 */
export function megabytes(bytes: number): number {
  return Math.floor(bytes / (1024 * 1024));
}
