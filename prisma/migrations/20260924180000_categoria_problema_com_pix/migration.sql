-- Категория «Problema com Pix» (§5, §11).
--
-- IF NOT EXISTS намеренно: значение добавляется в базу до выката кода, иначе
-- между выкатом и миграцией любое дело этой категории не сохранилось бы.
-- Повторный прогон миграции после этого обязан быть безвредным.
ALTER TYPE "CaseCategory" ADD VALUE IF NOT EXISTS 'PROBLEMA_COM_PIX';
